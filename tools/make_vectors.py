"""Writes the protocol's test vectors from the Python reference implementation.

    python3 tools/make_vectors.py tests/vectors/protocol-v1.json

The inputs (keys, nonces, messages) are fixed, so the output only changes when
the protocol does. CI regenerates the file and fails if it differs from the one
committed, so code and vectors can't drift apart.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import nesto_protocol as p


def h(data: bytes) -> str:
    return data.hex()


def fixed(label: str, size: int = 32) -> bytes:
    """Deterministic, distinct bytes for each input."""
    return bytes((i * 7 + sum(label.encode())) % 256 for i in range(size))


def pairing() -> dict:
    ha_private = fixed("ha-ephemeral")
    panel_private = fixed("panel-ephemeral")
    ha_pub = p.public_key(ha_private)
    panel_pub = p.public_key(panel_private)
    shared = p.shared_secret(ha_private, panel_pub)
    assert shared == p.shared_secret(panel_private, ha_pub)
    key = p.pairing_key(shared, ha_pub, panel_pub)
    return {
        "ha_private": h(ha_private),
        "panel_private": h(panel_private),
        "ha_public": h(ha_pub),
        "panel_public": h(panel_pub),
        "shared_secret": h(shared),
        "code": p.pairing_code(ha_pub, panel_pub, shared),
        "pairing_key": h(key),
        "confirm_mac_ha": h(p.confirm_mac(key, p.ROLE_HA)),
        "confirm_mac_panel": h(p.confirm_mac(key, p.ROLE_PANEL)),
    }


def session(key: bytes) -> dict:
    panel_nonce = fixed("panel-nonce", 16)
    ha_nonce = fixed("ha-nonce", 16)
    panel_id = "18b4300a1b2c"
    k_hp, k_ph = p.session_keys(key, panel_nonce, ha_nonce)

    frames = []
    messages = [
        ("h2p", k_hp, 0, {"t": "ping", "seq": 1}),
        ("h2p", k_hp, 1, {"t": "display", "id": 30, "state": "off"}),
        ("p2h", k_ph, 0, {"t": "ready"}),
        (
            "p2h",
            k_ph,
            1,
            {"t": "intent", "id": 12, "key": "l1", "action": "turn_on", "args": {"brightness": 40}},
        ),
        # A counter beyond 32 bits checks all eight counter bytes are used.
        ("p2h", k_ph, (1 << 32) + 5, {"t": "pong", "seq": 9}),
    ]
    for direction, k, counter, message in messages:
        plaintext = json.dumps(message, separators=(",", ":")).encode()
        sealed = p.seal(k, counter, plaintext)
        assert p.open_frame(k, counter, sealed) == plaintext
        frames.append(
            {
                "direction": direction,
                "counter": counter,
                "plaintext": plaintext.decode(),
                "frame": h(sealed),
            }
        )

    return {
        "pairing_key": h(key),
        "panel_id": panel_id,
        "panel_nonce": h(panel_nonce),
        "ha_nonce": h(ha_nonce),
        "auth_mac_ha": h(p.auth_mac(key, p.ROLE_HA, panel_nonce, ha_nonce, panel_id)),
        "auth_mac_panel": h(p.auth_mac(key, p.ROLE_PANEL, panel_nonce, ha_nonce, panel_id)),
        "key_h2p": h(k_hp),
        "key_p2h": h(k_ph),
        "frames": frames,
    }


def rfc8439() -> dict:
    """RFC 8439 section 2.8.2, to anchor the AEAD to the standard itself."""
    key = bytes(range(0x80, 0xA0))
    nonce = bytes.fromhex("070000004041424344454647")
    aad = bytes.fromhex("50515253c0c1c2c3c4c5c6c7")
    plaintext = (
        b"Ladies and Gentlemen of the class of '99: If I could offer you "
        b"only one tip for the future, sunscreen would be it."
    )
    sealed = p.ChaCha20Poly1305(key).encrypt(nonce, plaintext, aad)
    assert sealed[-16:].hex() == "1ae10b594f09e26a7e902ecbd0600691"
    return {
        "key": h(key),
        "nonce": h(nonce),
        "aad": h(aad),
        "plaintext": h(plaintext),
        "ciphertext_and_tag": h(sealed),
    }


def main() -> None:
    pair = pairing()
    vectors = {
        "comment": "Generated by tools/make_vectors.py from tools/nesto_protocol.py. Do not edit.",
        "protocol": 1,
        "pairing": pair,
        "session": session(bytes.fromhex(pair["pairing_key"])),
        "rfc8439": rfc8439(),
    }
    out = json.dumps(vectors, indent=2) + "\n"
    if len(sys.argv) > 1:
        Path(sys.argv[1]).write_text(out, encoding="utf-8", newline="\n")
    else:
        sys.stdout.write(out)


if __name__ == "__main__":
    main()
