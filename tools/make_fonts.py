import re
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

TEXT_RANGES = [
    (0x0020, 0x007E),  # ASCII
    (0x00A0, 0x00FF),  # Latin-1, with the degree sign
    (0x0100, 0x017F),  # Latin Extended-A, with Esperanto's letters
]
TEXT_EXTRA = [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x20AC]

