def mdi_codepoints(scss: Path) -> dict[str, int]:
    pattern = re.compile(r'^\s*"([a-z0-9-]+)":\s*([0-9A-F]+),', re.MULTILINE)
    return {name: int(code, 16) for name, code in pattern.findall(scss.read_text())}


def subset_font(path: Path, unicodes: list[int], keep_kerning: bool) -> bytes:
    options = subset.Options()
    options.layout_features = ["kern"] if keep_kerning else []
    options.name_IDs = ["*"]  # keep copyright and licence names
    options.notdef_outline = True
    options.hinting = False  # tiny_ttf doesn't use hinting
    font = TTFont(path)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=unicodes)
    subsetter.subset(font)
    out = io.BytesIO()
    font.save(out)
    return out.getvalue()


def c_array(name: str, data: bytes) -> str:
    rows = [
        "  " + ", ".join(f"0x{b:02x}" for b in data[i : i + 16]) + ","
        for i in range(0, len(data), 16)
    ]
    return (
        f"// {len(data)} bytes\n"
        f"alignas(4) const unsigned char {name}[] = {{\n" + "\n".join(rows) + "\n};\n"
        f"const std::size_t {name}_size = sizeof {name};\n"
    )


def main() -> None:
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    text_ttf, mdi_ttf, mdi_scss, output = (Path(a) for a in sys.argv[1:])

    codes = mdi_codepoints(mdi_scss)
    missing = sorted(mdi for mdi in ICONS.values() if mdi not in codes)
    if missing:
        sys.exit(f"icons missing from Material Design Icons: {', '.join(missing)}")

    text_unicodes = [c for lo, hi in TEXT_RANGES for c in range(lo, hi + 1)] + TEXT_EXTRA
    text = subset_font(text_ttf, text_unicodes, keep_kerning=True)
    icons = subset_font(mdi_ttf, sorted({codes[m] for m in ICONS.values()}), keep_kerning=False)

    def utf8_escaped(code: int) -> str:
        return "".join(f"\\x{b:02x}" for b in chr(code).encode("utf-8"))

    table = "\n".join(
        f'    {{"{name}", "{utf8_escaped(codes[mdi])}"}},' for name, mdi in sorted(ICONS.items())
    )
    output.write_text(
        "// Generated by tools/make_fonts.py. Do not edit.\n"
        "// Montserrat (SIL Open Font License 1.1) and Material Design Icons\n"
        "// (Apache License 2.0); see THIRD_PARTY.md.\n"
        '#include "app/FontData.hpp"\n\n'
        "#include <cstring>\n\n"
        "namespace nesto::fonts {\n\n"
        + c_array("text_ttf", text)
        + "\n"
        + c_array("icons_ttf", icons)
        + "\nnamespace {\n\n"
        "struct Icon {\n  const char* name;\n  const char* utf8;\n};\n\n"
        "const Icon kIcons[] = {\n" + table + "\n};\n\n"
        "}  // namespace\n\n"
        "const char* icon(const char* name) {\n"
        "  for (const Icon& i : kIcons) {\n"
        "    if (std::strcmp(i.name, name) == 0) return i.utf8;\n"
        "  }\n"
        '  return "";\n'
        "}\n\n"
        "}  // namespace nesto::fonts\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"text font {len(text)} bytes, icon font {len(icons)} bytes, {len(ICONS)} icons")


if __name__ == "__main__":
    main()
