"""Builds the panel's fonts into a C++ source file.

    python3 tools/make_fonts.py TEXT_TTF MDI_TTF MDI_SCSS OUTPUT_CPP

Run by the build (see cmake/Dependencies.cmake), not by hand. It keeps only what
the panel draws, so the fonts stay small enough to embed:

- the text font (Montserrat) with Latin-1 and Latin Extended-A, which cover
  Spanish, Esperanto and most European languages, the degree sign and a little
  punctuation;
- the icon font (Material Design Icons, the set Home Assistant uses) with the
  icons below.

LVGL draws both at runtime with its TrueType renderer (tiny_ttf).
"""

from __future__ import annotations

